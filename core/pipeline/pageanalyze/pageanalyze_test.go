package pageanalyze

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"testing"
)

// writePGM writes a synthetic P5 (binary, 8-bit) PGM. Every pixel
// takes the same value — good enough for whiteness-mean tests.
func writePGM(t *testing.T, path string, width, height, value int) {
	t.Helper()
	if value < 0 || value > 255 {
		t.Fatalf("bad value %d", value)
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "P5\n%d %d\n255\n", width, height)
	pix := bytes.Repeat([]byte{byte(value)}, width*height)
	buf.Write(pix)
	if err := os.WriteFile(path, buf.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestMeanWhitePGM_AllWhite(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "white.pgm")
	writePGM(t, p, 10, 10, 255)
	m, err := meanWhitePGM(p)
	if err != nil {
		t.Fatal(err)
	}
	if m != 1.0 {
		t.Errorf("all-white PGM should be 1.0, got %v", m)
	}
}

