func TestMeanWhitePGM_Mid(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "mid.pgm")
	writePGM(t, p, 20, 20, 128)
	m, err := meanWhitePGM(p)
	if err != nil {
		t.Fatal(err)
	}
	want := 128.0 / 255.0
	if diff := m - want; diff > 0.001 || diff < -0.001 {
		t.Errorf("got %v want ~%v", m, want)
	}
}

func TestMeanWhitePGM_WithComments(t *testing.T) {
	// PGM comments are legal between header tokens; make sure we skip them.
	dir := t.TempDir()
	p := filepath.Join(dir, "commented.pgm")
	var buf bytes.Buffer
	buf.WriteString("P5\n")
	buf.WriteString("# generated by test\n")
	buf.WriteString("4 2\n")
	buf.WriteString("# maxval below\n")
	buf.WriteString("255\n")
	buf.Write(bytes.Repeat([]byte{200}, 8))
	if err := os.WriteFile(p, buf.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	m, err := meanWhitePGM(p)
	if err != nil {
		t.Fatal(err)
	}
	want := 200.0 / 255.0
	if diff := m - want; diff > 0.001 || diff < -0.001 {
		t.Errorf("commented PGM: got %v want ~%v", m, want)
	}
}

func TestListPGMs_NumericOrder(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{"p-10.pgm", "p-2.pgm", "p-1.pgm", "unrelated.txt"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	got, err := listPGMs(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := []int{1, 2, 10}
	if len(got) != len(want) {
		t.Fatalf("got %v want len %d", got, len(want))
	}
	for i, g := range got {
		if g.n != want[i] {
			t.Errorf("[%d] got %d want %d", i, g.n, want[i])
		}
	}
}
